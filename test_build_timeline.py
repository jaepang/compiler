"""build_timeline.py 오프라인 테스트 — ffmpeg 로 초소형 미디어를 진짜로 만들어 FCPXML/SRT/description 을 검증한다 (네트워크 없음)"""
import shutil, subprocess, sys, tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import unquote, urlparse
sys.path.insert(0, str(Path(__file__).parent))
import playlist_dl as pdl
import build_timeline as bt

FFMPEG = shutil.which("ffmpeg"); assert FFMPEG, "ffmpeg 가 PATH 에 없음"
def ff(*a): subprocess.run([FFMPEG, "-v", "error", "-y", *a], check=True)
def src_path(el): return Path(unquote(urlparse(el.get("src")).path))
def frames_of(s): return 0 if s == "0s" else int(s.split("/")[0])

print("== 시간 표기 ==")
assert bt.chapter_ts(0, 30) == "00:00" and bt.chapter_ts(75, 30) == "00:02" and bt.chapter_ts(3661 * 30, 30) == "1:01:01"
assert bt.srt_ts(75, 30) == "00:00:02,500" and bt.srt_ts(0, 25) == "00:00:00,000"
assert bt.frame_time(0, 30) == "0s" and bt.frame_time(75, 30) == "75/30s"

print("== 프로젝트 준비 (ffmpeg 합성) ==")
root = Path(tempfile.mkdtemp()); proj = root / "01.테스트"; dl = proj / "downloads"; dl.mkdir(parents=True)
ff("-f", "lavfi", "-i", "sine=frequency=440:duration=2.5", "-f", "lavfi", "-i", "color=c=red:s=64x64:d=1",
   "-map", "0:a", "-map", "1:v", "-frames:v", "1", "-c:a", "aac", "-c:v", "png", "-disposition:v:0", "attached_pic",
   "-metadata", "description=Provided to YouTube by TestLabel\n\n노래 · 가수\n\n앨범\n\nAuto-generated by YouTube.",
   "-metadata", "comment=https://www.youtube.com/watch?v=aaa", str(dl / "01.가수-노래.m4a"))           # 커버 PNG + 배급사 태그
ff("-f", "lavfi", "-i", "sine=frequency=880:duration=1.0", "-c:a", "aac", str(dl / "02.둘-Second_Song.m4a"))   # 커버 없음
ff("-f", "lavfi", "-i", "testsrc=size=320x240:rate=30:duration=1.5", "-f", "lavfi", "-i", "sine=frequency=660:duration=1.5",
   "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", "-metadata", "comment=https://www.youtube.com/watch?v=ccc",
   str(dl / "03.Band-Live_Show.mp4"))                                                                        # 영상
def dec(i, vid, title, name, ch, mode, artist):
    return pdl.Decision(index=i, id=vid, title=title, name=name, channel=ch, duration=2, mode=mode, reason="r",
                        url=f"https://www.youtube.com/watch?v={vid}", artist=artist)
items = [dec(1, "aaa", "노래", "가수-노래", "가수 - Topic", "audio", "가수"),
         dec(2, "bbb", "Second Song", "둘-Second Song", "둘 - Topic", "audio", "둘"),
         dec(3, "ccc", "Band - Live Show", "Band-Live Show", "BandVEVO", "video", "Band")]
pdl.write_manifest(proj, "https://x/pl", "테스트 목록", items)
assert bt.track_label(items[0]) == "가수 - 노래" and bt.track_label(items[2]) == "Band - Live Show"
assert bt.track_label(pdl.Decision(**{**pdl.asdict(items[0]), "artist": "", "name": "옛이름"})) == "옛이름"   # 구버전 항목

print("== build (fps 30, gap 0) ==")
res = bt.build(proj, fps=30)
build = proj / "build"
assert res.fcpxml == build / "timeline.fcpxml" and res.srt == build / "tracklist.srt" and res.description == build / "description.md"
assert all(p.exists() for p in (res.fcpxml, res.srt, res.description)), list(build.iterdir())
durs = [round(bt.probe(dl / f)["duration"] * 30) for f in ("01.가수-노래.m4a", "02.둘-Second_Song.m4a", "03.Band-Live_Show.mp4")]
assert [t.frames for t in res.tracks] == durs and [t.start for t in res.tracks] == [0, durs[0], durs[0] + durs[1]], (res.tracks, durs)

tree = ET.parse(res.fcpxml); fx = tree.getroot()
assert fx.tag == "fcpxml" and fx.get("version") == "1.8"
fmt = fx.find("resources/format"); assert (fmt.get("width"), fmt.get("height"), fmt.get("frameDuration")) == ("1920", "1080", "1/30s")
assets = {a.get("id"): a for a in fx.findall("resources/asset")}
for a in assets.values():
    assert src_path(a).exists(), a.get("src")                       # 절대경로 file:// 이 실제 파일을 가리킨다
seq = fx.find(".//sequence"); assert seq.get("format") == "r1" and frames_of(seq.get("duration")) == sum(durs)
spine = list(seq.find("spine"))
assert [e.tag for e in spine] == ["video", "video", "asset-clip"], [e.tag for e in spine]
assert [frames_of(e.get("offset")) for e in spine] == [0, durs[0], durs[0] + durs[1]]
assert [frames_of(e.get("duration")) for e in spine] == durs
# 음원 곡: 스파인은 커버 정지 이미지(<video>, asset duration 0s), 음원은 lane -1 에 연결
for e, cover_name in zip(spine[:2], ("01.png", "black.png")):
    still = assets[e.get("ref")]
    assert still.get("duration") == "0s" and still.get("hasVideo") == "1" and src_path(still).name == cover_name, (still.attrib, cover_name)
    audio = e.find("asset-clip"); a = assets[audio.get("ref")]
    assert audio.get("lane") == "-1" and audio.get("offset") == "0s" and audio.get("duration") == e.get("duration")
    assert a.get("hasAudio") == "1" and a.get("hasVideo") == "0" and src_path(a).suffix == ".m4a"
assert src_path(assets[spine[0].get("ref")]).read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"   # 실제 커버가 추출됨
# 영상 곡: mp4 자체가 스파인
v = assets[spine[2].get("ref")]; assert v.get("hasVideo") == "1" and v.get("hasAudio") == "1" and src_path(v).suffix == ".mp4"
labels = ["가수 - 노래", "둘 - Second Song", "Band - Live Show"]
assert [e.get("name") for e in spine] == labels
assert [e.find("marker").get("value") for e in spine] == [f"{i:02d} {l}" for i, l in enumerate(labels, 1)]
assert all(e.find("marker").get("start") == "0s" for e in spine)
assert fx.find(".//project").get("name") == "테스트 목록"

srt = res.srt.read_text(encoding="utf-8").strip().split("\n\n")
assert len(srt) == 3 and srt[0].split("\n") == ["1", f"00:00:00,000 --> {bt.srt_ts(durs[0], 30)}", "가수 - 노래"], srt[0]
assert srt[2].split("\n")[1] == f"{bt.srt_ts(durs[0] + durs[1], 30)} --> {bt.srt_ts(sum(durs), 30)}"

desc = res.description.read_text(encoding="utf-8")
assert "00:00 가수 - 노래" in desc and f"{bt.chapter_ts(durs[0], 30)} 둘 - Second Song" in desc, desc
assert "Provided to YouTube by TestLabel" in desc and "https://www.youtube.com/watch?v=aaa" in desc and "BandVEVO" in desc, desc
print("  fcpxml/srt/description OK")

print("== gap 1.0 / fps 25 ==")
res2 = bt.build(proj, fps=30, gap=1.0)
spine2 = list(ET.parse(res2.fcpxml).getroot().find(".//spine"))
assert [e.tag for e in spine2] == ["video", "gap", "video", "gap", "asset-clip"], [e.tag for e in spine2]
assert all(frames_of(g.get("duration")) == 30 for g in spine2 if g.tag == "gap")
assert [frames_of(e.get("offset")) for e in spine2 if e.tag != "gap"] == [0, durs[0] + 30, durs[0] + durs[1] + 60]
assert frames_of(ET.parse(res2.fcpxml).getroot().find(".//sequence").get("duration")) == sum(durs) + 60
assert f"{bt.chapter_ts(durs[0] + 30, 30)} 둘 - Second Song" in res2.description.read_text(encoding="utf-8")
res3 = bt.build(proj, fps=25)
assert ET.parse(res3.fcpxml).getroot().find("resources/format").get("frameDuration") == "1/25s"
assert [t.frames for t in res3.tracks] == [round(bt.probe(dl / f)["duration"] * 25) for f in ("01.가수-노래.m4a", "02.둘-Second_Song.m4a", "03.Band-Live_Show.mp4")]
print("  OK")

print("== mix 모드 (--audio [--cues]): GarageBand 믹스의 곡 경계(cues)가 V1 배치·마커·자막·챕터가 된다 ==")
import build_daw as bd
daw = bd.build(proj)                              # WAV·무음 영상
wav = {t.decision.index: t.wav for t in daw.tracks}
mix = proj / "build" / "daw" / "mix.wav"
ff("-f", "lavfi", "-i", "sine=frequency=440:duration=6.0", "-ar", "48000", "-c:a", "pcm_s16le", str(mix))
cues_path = proj / "build" / "daw" / "cues.json"
d1 = bt.probe(wav[1])["duration"]
bd.save_cues(cues_path, [bd.Cue(1, "가수 - 노래", 0.0, d1, 0.0, wav[1]),
                         bd.Cue(3, "Band - Live Show", d1 + 0.5, 1.0, 0.25, wav[3]),   # 영상 곡: 앞 0.25초 트림
                         bd.Cue(2, "둘 - Second Song", 5.0, 0.5, 0.0, wav[2])])       # 2번 곡을 맨 뒤로
try:
    bt.build(proj, fps=30, cues=cues_path); raise AssertionError("--audio 없이 통과")
except bt.BuildError as e:
    assert "--audio" in str(e), e
res = bt.build(proj, fps=30, audio=mix, cues=cues_path)
assert [t.decision.index for t in res.tracks] == [1, 3, 2]
assert [t.start for t in res.tracks] == [0, round((d1 + 0.5) * 30), 150] and [t.frames for t in res.tracks] == [round(d1 * 30), 30, 15], res.tracks
fx = ET.parse(res.fcpxml).getroot(); assets = {a.get("id"): a for a in fx.findall("resources/asset")}
seq = fx.find(".//sequence"); spine = list(seq.find("spine"))
assert len(spine) == 1 and spine[0].tag == "asset-clip", [e.tag for e in spine]                 # 스파인 = mix 한 클립
mixa = assets[spine[0].get("ref")]
assert (mixa.get("hasAudio"), mixa.get("hasVideo")) == ("1", "0") and src_path(mixa) == mix and spine[0].get("duration") == "180/30s"
assert frames_of(seq.get("duration")) == 180
conn = [e for e in spine[0] if e.tag in ("video", "asset-clip")]
assert [e.tag for e in conn] == ["video", "asset-clip", "video"] and all(e.get("lane") == "1" for e in conn), [(e.tag, e.get("lane")) for e in conn]
assert [frames_of(e.get("offset")) for e in conn] == [t.start for t in res.tracks]
assert [frames_of(e.get("duration")) for e in conn] == [round((d1 + 0.5) * 30), 30, 30], [e.get("duration") for e in conn]   # 커버는 다음 곡/믹스 끝까지(hold), 영상은 곡 길이
assert [t.hold for t in res.tracks] == [round((d1 + 0.5) * 30), 0, 30]
v = assets[conn[1].get("ref")]                                                                   # 영상 곡: 무음 mp4, 트림 반영
assert v.get("hasAudio") == "0" and src_path(v).parent.name == "video" and src_path(v).suffix == ".mp4", v.attrib
assert conn[1].get("start") == "8/30s", conn[1].get("start")                                     # 0.25s → 8프레임
assert [e.find("marker").get("value") for e in conn] == ["01 가수 - 노래", "03 Band - Live Show", "02 둘 - Second Song"]
srt = res.srt.read_text(encoding="utf-8").strip().split("\n\n")
assert srt[2].split("\n")[1:] == [f"{bt.srt_ts(150, 30)} --> {bt.srt_ts(165, 30)}", "둘 - Second Song"], srt[2]
desc = res.description.read_text(encoding="utf-8")
assert desc.index("Band - Live Show") < desc.index("둘 - Second Song") and "00:05 둘 - Second Song" in desc, desc
# --cues 없이 --audio 만 주면 align_cues 로 경계를 찾고 cues.json 을 새로 쓴다 (내용 검증은 test_build_daw 에서)
cues_path.unlink()
_align = bd.align_cues
bd.align_cues = lambda m, tracks, ffmpeg=None: [bd.Cue(t.decision.index, t.label, i * 1.0, 0.9, 0.0, t.wav, 0.9) for i, t in enumerate(tracks)]
res2 = bt.build(proj, fps=30, audio=mix)
bd.align_cues = _align
assert cues_path.exists() and [t.decision.index for t in res2.tracks] == [1, 2, 3] and [t.start for t in res2.tracks] == [0, 30, 60]
print("  mix 모드 OK")

print("== 파일 누락 ==")
(dl / "02.둘-Second_Song.m4a").unlink()
try:
    bt.build(proj, fps=30); raise AssertionError("누락인데 통과")
except bt.BuildError as e:
    assert "02" in str(e) and "restore" in str(e), e
print("  BuildError OK")
shutil.rmtree(root, ignore_errors=True)
print("\nALL OK")
