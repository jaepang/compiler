class YtDlpError(RuntimeError):
    pass


def find_ytdlp(explicit: str | None) -> str:
    exe = shutil.which(explicit or "yt-dlp")
    if not exe:
        sys.exit(
            f"yt-dlp 실행 파일을 찾을 수 없습니다 ({explicit or 'yt-dlp'}). "
            "brew install yt-dlp 로 설치하거나 --yt-dlp 로 경로를 지정하세요."
        )
    return exe


def common_args(args) -> list[str]:
    a = ["--no-playlist", "--retries", "5", "--fragment-retries", "5"]
    if args.cookies_from_browser:
        a += ["--cookies-from-browser", args.cookies_from_browser]
    if args.cookies:
        a += ["--cookies", args.cookies]
    if args.windows_filenames:
        a += ["--windows-filenames"]
    if args.quiet:
        a += ["--no-warnings"]
    return a


def run_json(ytdlp: str, cli_args: list[str]) -> dict:
    """yt-dlp -J … 를 실행해 JSON 을 돌려준다"""
    proc = subprocess.run([ytdlp, "-J", *cli_args], capture_output=True, text=True)
    if proc.returncode != 0 or not proc.stdout.strip():
        err = (proc.stderr or "").strip().splitlines()
        raise YtDlpError(err[-1] if err else f"yt-dlp exit {proc.returncode}")
    try:
        return json.loads(proc.stdout.strip().splitlines()[-1])
    except json.JSONDecodeError as e:
        raise YtDlpError(f"JSON 파싱 실패: {e}") from e


def fetch_playlist(ytdlp: str, url: str, args) -> tuple[str, list[dict]]:
    """재생목록 제목과 (flat) 엔트리 목록"""
    a = [x for x in common_args(args) if x != "--no-playlist"]
    pl = run_json(ytdlp, [*a, "--flat-playlist", "--yes-playlist", url])
    entries = [e for e in (pl.get("entries") or []) if e and e.get("id")]
    return pl.get("title") or pl.get("id") or "playlist", entries


def fetch_info(ytdlp: str, url: str, args) -> dict:
    """영상 하나의 전체 메타데이터 (설명·태그·포맷·스토리보드 포함)"""
    return run_json(ytdlp, [*common_args(args), url])


def mode_args(mode: str, args, base_dir: Path, index: int, name: str) -> list[str]:
    """모드별 다운로드 인자"""
    out = outtmpl_for(base_dir / "downloads", index, name)
    a = ["-o", out, "--embed-metadata", "--download-archive", str(base_dir / f"archive_{mode}.txt")]
    if not args.no_thumbnail:
        a.append("--embed-thumbnail")
    if mode == "audio":
        if args.audio_codec == "aac":
            # AAC 스트림만 후보로 → 비트레이트 순 (프리미엄 141=256k > 140=128k). AAC 가 없을 때만 최고 오디오를 AAC 로 변환.
            # --audio-format m4a: 이미 AAC 면 컨테이너만 .m4a 로, 아니면 AAC 로 인코딩 (--audio-quality 0 = 최고 VBR)
            a += ["-f", "bestaudio[acodec^=mp4a]/bestaudio/best", "-S", "abr",
                  "-x", "--audio-format", "m4a", "--audio-quality", "0"]
        else:
            # 코덱 무관 최고 비트레이트, 재인코딩 없이 원본 코덱 유지 (opus→.opus, aac→.m4a)
            a += ["-f", "bestaudio/best", "-S", "abr", "-x", "--audio-format", "best"]
    else:
        if args.video_container == "mp4":
            # yt-dlp 의 `-t mp4` 프리셋과 같은 정렬: H.264 를 해상도보다 먼저 → 편집기·YouTube 호환. 오디오는 AAC 우선.
            a += ["-f", "bestvideo*+bestaudio/best", "-S", "vcodec:h264,res,fps,hdr:12,acodec:aac",
                  "--merge-output-format", "mp4", "--remux-video", "mp4"]
        else:
            # 해상도 → fps → 코덱 순 최고 영상 + 최고 오디오를 그대로 병합
            a += ["-f", "bestvideo*+bestaudio/best", "--merge-output-format", args.video_container]
    return a


DRY_RUN_TEMPLATE = "%(format_id)s|%(resolution)s|%(fps)s|%(vcodec)s|%(acodec)s|%(abr)s"


def format_dry_line(raw: str) -> str:
    """--print 결과 한 줄을 사람이 읽기 좋게: '313+141  3840x2160@30fps vp9 + mp4a.40.2 256k'"""
    parts = (raw.split("|") + [""] * 6)[:6]
    fid, res, fps, vcodec, acodec, abr = (p if p not in ("NA", "None") else "" for p in parts)
    def num(x: str, unit: str) -> str:
        try:
            v = float(x)
        except ValueError:
            return ""
        return f"{v:g}{unit}"

    out = []
    if vcodec and vcodec != "none":
        fps_s = num(fps, "fps")
        out.append(f"{res}{'@' + fps_s if fps_s else ''} {vcodec}".strip())
    if acodec and acodec != "none":
        abr_s = num(abr, "k")
        out.append(f"{acodec}{' ' + abr_s if abr_s else ''}")
    return f"{fid}  {' + '.join(out)}".strip()


def dry_run(ytdlp: str, url: str, args, mode: str, base_dir: Path, index: int, name: str) -> str:
    """--print 로 선택될 포맷과 파일명만 확인 (--print 는 --simulate 를 함축)"""
    cmd = [ytdlp, *common_args(args), *mode_args(mode, args, base_dir, index, name),
           "--print", DRY_RUN_TEMPLATE, "--print", "filename", url]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    lines = [l for l in proc.stdout.splitlines() if l.strip()]
    if proc.returncode != 0 and not lines:
        err = (proc.stderr or "").strip().splitlines()
        raise YtDlpError(err[-1] if err else f"yt-dlp exit {proc.returncode}")
    if len(lines) < 2:
        return "(archive 에 이미 기록됨 — 건너뜀)"
    fmt = format_dry_line(lines[0])
    fn = Path(lines[1]).name
    if mode == "audio":  # -x 후 확장자
        fn = re.sub(r"\.(webm|opus|ogg|mp4)$", ".m4a" if args.audio_codec == "aac" else ".opus", fn)
    elif args.video_container == "mp4":
        fn = re.sub(r"\.(webm|mkv)$", ".mp4", fn)
    return f"{fmt}  →  downloads/{fn}"


def download(ytdlp: str, url: str, args, mode: str, base_dir: Path, index: int, name: str) -> None:
    cmd = [ytdlp, *common_args(args), *mode_args(mode, args, base_dir, index, name), url]
    proc = subprocess.run(cmd)  # 진행률은 yt-dlp 가 터미널에 직접 출력
    if proc.returncode != 0:
        raise YtDlpError(f"yt-dlp exit {proc.returncode}")


# --------------------------------------------------------------------------- 매니페스트 (classification.json)

MANIFEST_NAME = "classification.json"


def write_manifest(base_dir: Path, playlist_url: str, playlist_title: str, decisions: list[Decision]) -> Path:
    """분류 결과 + 재생목록 정보 저장. 다른 머신에서 --restore 로 같은 파일명·포맷을 재현하는 근거"""
    base_dir.mkdir(parents=True, exist_ok=True)
    path = base_dir / MANIFEST_NAME
    doc = {"playlist": {"url": playlist_url, "title": playlist_title}, "items": [asdict(d) for d in decisions]}
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def read_manifest(base_dir: Path) -> tuple[dict, list[Decision]]:
    """(재생목록 정보, 항목). 구버전(항목 리스트만 있는) 파일은 재생목록 정보 {} 로 읽힌다"""
    doc = json.loads((base_dir / MANIFEST_NAME).read_text(encoding="utf-8"))
    if isinstance(doc, list):
        return {}, [Decision(**d) for d in doc]
    return doc.get("playlist") or {}, [Decision(**d) for d in doc.get("items") or []]


def discover_projects(root: Path) -> list[Path]:
    """root 바로 아래에서 매니페스트를 가진 프로젝트 폴더를 이름순으로"""
    return sorted(m.parent for m in root.glob(f"*/{MANIFEST_NAME}"))


# --------------------------------------------------------------------------- 복원 대상 선택 (curses TUI)

ALL_LABEL = "전부 복원"


def display_width(s: str) -> int:
    """터미널 칸 수 (한글 등 전각은 2칸) — curses 에서 줄 폭을 맞출 때"""
    return sum(2 if unicodedata.east_asian_width(ch) in "WF" else 1 for ch in s)


def fit_width(s: str, cols: int) -> str:
    """display_width 기준으로 cols 칸 안에 들어가게 자른다"""
    out, used = [], 0
    for ch in s:
        w = 2 if unicodedata.east_asian_width(ch) in "WF" else 1
        if used + w > cols:
            break
        out.append(ch)
        used += w
    return "".join(out)


class Picker:
    """체크박스 목록 상태. 0번 행은 '전부 복원'(전체 토글), 1번부터 프로젝트. 화면은 pick_projects 가 그린다"""

    def __init__(self, labels: list[str]):
        self.labels = labels
        self.checked = [False] * len(labels)
        self.cursor = 0

    @property
    def all_checked(self) -> bool:
        return bool(self.checked) and all(self.checked)

    def move(self, delta: int) -> None:
        self.cursor = max(0, min(len(self.labels), self.cursor + delta))

    def toggle(self) -> None:
        if self.cursor == 0:
            self.toggle_all()
        else:
            self.checked[self.cursor - 1] = not self.checked[self.cursor - 1]

    def toggle_all(self) -> None:
        self.checked = [not self.all_checked] * len(self.labels)

    def selected(self) -> list[int]:
        return [i for i, c in enumerate(self.checked) if c]

    def rows(self) -> list[tuple[bool, str]]:
        return [(self.all_checked, ALL_LABEL)] + list(zip(self.checked, self.labels))


def project_label(base_dir: Path) -> str:
    meta, items = read_manifest(base_dir)
    n_a = sum(d.mode == "audio" for d in items)
    return f"{base_dir.name}  — '{meta.get('title') or '?'}' {len(items)}개 (음원 {n_a} · 영상 {len(items) - n_a})"


def pick_projects(projects: list[Path]) -> list[Path] | None:
    """↑↓/j k 이동, space 토글, a 전부 토글, Enter 확정, q/Esc 취소(None). 표준 라이브러리 curses 만 사용"""
    import curses
    import locale

    locale.setlocale(locale.LC_ALL, "")  # 한글을 터미널 인코딩으로 그리기 위해
    picker = Picker([project_label(p) for p in projects])

    def loop(scr):
        curses.curs_set(0)
        scr.keypad(True)
        msg = ""
        while True:
            scr.erase()
            h, w = scr.getmaxyx()

            def put(y, text, attr=0):
                if 0 <= y < h:
                    try:
                        scr.addstr(y, 0, fit_width(text, w - 1), attr)
                    except curses.error:  # 화면 끝 모서리 등 그리기 실패는 무시
                        pass

            put(0, "복원할 프로젝트를 고르세요", curses.A_BOLD)
            put(1, "↑↓ / j k 이동   space 토글   a 전부   Enter 확정   q 취소")
            for i, (checked, label) in enumerate(picker.rows()):
                put(3 + i, f" [{'x' if checked else ' '}] {label}", curses.A_REVERSE if i == picker.cursor else 0)
            if msg:
                put(h - 1, msg, curses.A_BOLD)
            scr.refresh()

            key = scr.getch()
            msg = ""
            if key in (curses.KEY_UP, ord("k")):
                picker.move(-1)
            elif key in (curses.KEY_DOWN, ord("j")):
                picker.move(1)
            elif key == ord(" "):
                picker.toggle()
            elif key == ord("a"):
                picker.toggle_all()
            elif key in (curses.KEY_ENTER, 10, 13):
                if picker.selected():
                    return picker.selected()
                msg = "선택된 항목이 없습니다 — space 로 체크하거나 q 로 취소"
            elif key in (27, ord("q")):
                return None

    chosen = curses.wrapper(loop)
    return None if chosen is None else [projects[i] for i in chosen]


# --------------------------------------------------------------------------- 복원


def restore(ytdlp: str, args, base_dir: Path) -> tuple[list[Decision], list[str]]:
    """매니페스트에 기록된 index/name/mode/url 그대로 내려받는다.
    재생목록 조회·분류를 하지 않으므로 재생목록이 바뀌었거나 pillow 가 없어도 원본 머신과 같은 파일명·포맷이 나온다.
    (완료 항목, 실패 ID) 반환. 매니페스트는 건드리지 않는다."""
    meta, items = read_manifest(base_dir)
    if args.only:
        items = [d for d in items if d.id in set(args.only)]
    (base_dir / "downloads").mkdir(parents=True, exist_ok=True)
    print(f"▶ 복원: {base_dir}  ('{meta.get('title') or '?'}', {len(items)}개 → {base_dir / 'downloads'})")

    done: list[Decision] = []
    failed: list[str] = []
    for d in items:
        tag = "♪ AUDIO" if d.mode == "audio" else "▶ VIDEO"
        print(f"[{d.index:02d}] {tag}  {d.name}")
        try:
            if args.dry_run:
                print(f"       → {dry_run(ytdlp, d.url, args, d.mode, base_dir, d.index, d.name)}")
            else:
                download(ytdlp, d.url, args, d.mode, base_dir, d.index, d.name)
            done.append(d)
        except YtDlpError as e:
            print(f"       ✗ 다운로드 실패: {e}")
            failed.append(d.id)
    return done, failed


def restore_main(ytdlp: str, args) -> int:
    """--restore [DIR ...]: DIR 이 없으면 현재 폴더의 프로젝트를 TUI 로 골라서"""
    if args.restore:
        targets = [Path(d).expanduser() for d in args.restore]
        missing = [str(t) for t in targets if not (t / MANIFEST_NAME).exists()]
        if missing:
            sys.exit(f"매니페스트({MANIFEST_NAME})가 없는 폴더: {', '.join(missing)}")
    else:
        projects = discover_projects(Path.cwd())
        if not projects:
            sys.exit(f"현재 폴더에 {MANIFEST_NAME} 을 가진 프로젝트가 없습니다. compiler 폴더에서 실행하거나 --restore DIR 로 지정하세요.")
        if not (sys.stdin.isatty() and sys.stdout.isatty()):
            sys.exit("선택 화면은 터미널에서만 열 수 있습니다. --restore DIR 로 대상을 지정하세요.")
        targets = pick_projects(projects)
        if targets is None:
            print("취소했습니다.")
            return 0

    all_failed: list[str] = []
    for t in targets:
        done, failed = restore(ytdlp, args, t)
        all_failed += failed
        print(f"  완료 {len(done)}개, 실패 {len(failed)}개\n")
    if all_failed:
        print("실패한 ID:", ", ".join(all_failed))
    return 1 if all_failed else 0


