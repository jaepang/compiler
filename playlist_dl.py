# 수동 오버라이드: 자동 판별이 애매하거나 틀린 영상은 여기에 적어 두면 항상 우선한다.
# 값은 "audio" 또는 "video". (2026-09-07 재생목록 19곡을 직접 확인해서 정리)
MANUAL_OVERRIDES: dict[str, str] = {
    # 16곡은 전부 "- Topic" 자동 생성 음원이라 2번 규칙으로 자동 처리됨. 아래는 나머지 3곡.
    "oGQ6Ykwha1E": "video",  # Nothing But Thieves - Ban All the Music (Live at The O2)  — 공연 실황
    "9wV9_je85DE": "video",  # Muse - Stockholm Syndrome [Live From Wembley Stadium]  — 공연 실황
    "E8-P833ptPk": "audio",  # NELL - Movie (Shoegaze Inst) [Unofficial] (빈도시)     — 정지 이미지 + 팬메이드 인스트
}

# 제목에 이런 단어가 있으면 '영상'으로 본다 (라이브·MV·퍼포먼스 계열)
VIDEO_HINTS = re.compile(
    r"\b(live|concert|m/v|mv|music\s*video|official\s*(music\s*)?video|performance|perf\.?|"
    r"session|sessions|tour|festival|unplugged|choreography|dance\s*practice|stage)\b"
    r"|라이브|실황|공연|콘서트|뮤직\s*비디오|뮤비|무대|안무|직캠",
    re.IGNORECASE,
)

# 제목에 이런 단어가 있으면 '음원'으로 본다
AUDIO_HINTS = re.compile(
    r"\b(official\s*audio|audio|lyrics?|lyric\s*video|inst\.?|instrumental|mr|off\s*vocal|"
    r"full\s*album|visualizer|remaster(ed)?|karaoke|8d|slowed|sped\s*up)\b"
    r"|가사|음원|전곡|앨범\s*전체|노래방|오디오",
    re.IGNORECASE,
)

# 스토리보드 프레임 간 평균 밝기 차이(0~255)가 이 값보다 작으면 '정지 이미지'로 본다.
# 실측: 정지 이미지 ≈ 0.8, Topic 앨범아트 ≈ 6 (JPEG 노이즈), 공연 실황 ≈ 20~60
MOTION_THRESHOLD = 10.0

