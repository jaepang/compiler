    p.add_argument("--audio-codec", default="aac", choices=["aac", "best"],
                   help="aac(기본): AAC/.m4a 로 통일 (편집기·YouTube 호환) / best: 코덱 무관 최고 비트레이트 원본 유지(opus 가능)")
    p.add_argument("--video-container", default="mp4", choices=["mp4", "mkv", "webm"],
                   help="mp4(기본): H.264+AAC 우선 (편집기·YouTube 호환) / mkv·webm: 코덱 무관 최고 해상도")
    p.add_argument("--windows-filenames", action="store_true", help="Windows 에서 쓸 수 없는 문자를 파일명에서 치환")
    p.add_argument("--cookies-from-browser", metavar="BROWSER", help="예: chrome, whale, safari, firefox")
    p.add_argument("--cookies", metavar="FILE", help="Netscape 형식 쿠키 파일")
    p.add_argument("--quiet", action="store_true")
    args = p.parse_args()

    if sys.platform.startswith("win"):
        args.windows_filenames = True
    ytdlp = find_ytdlp(args.ytdlp)

    if args.restore is not None:
        return restore_main(ytdlp, args)

    print(f"▶ 재생목록 조회: {args.url}  (yt-dlp: {ytdlp})")
    try:
        pl_title, entries = fetch_playlist(ytdlp, args.url, args)
    except YtDlpError as e:
        sys.exit(f"재생목록 조회 실패: {e}")
