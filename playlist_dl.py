def is_auto_generated_music(info: dict) -> bool:
    """YouTube Music 이 자동 생성한 '- Topic' 음원인지"""
    for key in ("uploader", "channel"):
        if str(info.get(key) or "").rstrip().endswith("- Topic"):
            return True
    desc = (info.get("description") or "").strip()
    if desc.startswith("Provided to YouTube by") or desc.endswith("Auto-generated by YouTube."):
        return True
    # yt-dlp 가 Topic 설명을 파싱하면 track/album 이 채워진다
    return bool(info.get("track") and info.get("album"))


def storyboard_motion(info: dict, timeout: float = 15.0) -> float | None:
    """스토리보드 첫 시트의 연속 프레임 간 평균 절대 밝기차(중앙값)를 계산. 실패 시 None."""
    try:
        from PIL import Image  # 선택 의존성
    except ImportError:
        return None

    boards = [f for f in info.get("formats") or [] if f.get("format_note") == "storyboard"]
    if not boards:
        return None
    # 너무 작은 타일은 노이즈가 커서 80px 이상 중 가장 작은 레벨을 고른다
    boards.sort(key=lambda f: f.get("width") or 0)
    board = next((f for f in boards if (f.get("width") or 0) >= 80), boards[-1])
    frags = board.get("fragments") or []
    rows, cols = board.get("rows"), board.get("columns")
    if not frags or not rows or not cols:
        return None

    try:
        with urllib.request.urlopen(frags[0]["url"], timeout=timeout) as resp:
            sheet = Image.open(io.BytesIO(resp.read())).convert("L")
    except Exception:
        return None

    tw, th = sheet.width // cols, sheet.height // rows
    tiles = []
    for r in range(rows):
        for c in range(cols):
            tile = sheet.crop((c * tw, r * th, (c + 1) * tw, (r + 1) * th))
            px = list(tile.getdata())
            if sum(px) / len(px) > 8:  # 시트 끝의 검은 빈 타일 제외
                tiles.append(px)
    if len(tiles) < 3:
        return None

    diffs = []
    for a, b in zip(tiles, tiles[1:]):
        diffs.append(sum(abs(x - y) for x, y in zip(a, b)) / len(a))
    return statistics.median(diffs)


def classify(info: dict, *, motion_check: bool = True) -> tuple[str, str]:
    """(mode, reason) 반환"""
    vid = info.get("id", "")
    title = info.get("title") or ""

    if vid in MANUAL_OVERRIDES:
        return MANUAL_OVERRIDES[vid], "manual override"

    if is_auto_generated_music(info):
        return "audio", "YouTube 자동 생성 음원 (- Topic)"

    if VIDEO_HINTS.search(title):
        return "video", f"제목 힌트: {VIDEO_HINTS.search(title).group(0)!r}"

    if AUDIO_HINTS.search(title):
        return "audio", f"제목 힌트: {AUDIO_HINTS.search(title).group(0)!r}"

    if motion_check:
        motion = storyboard_motion(info)
        if motion is not None:
            if motion < MOTION_THRESHOLD:
                return "audio", f"정지 이미지 (스토리보드 변화량 {motion:.1f})"
            return "video", f"움직이는 영상 (스토리보드 변화량 {motion:.1f})"

    return "video", "판별 불가 → 기본값 video"


# --------------------------------------------------------------------------- 파일명 (한글 우선)

HANGUL = re.compile(r"[가-힣]")
# "영문 (한글)" 또는 "영문 [한글]" 꼴: 괄호 안이 한글이면 그걸 제목으로
EN_WITH_KO_PAREN = re.compile(r"^\s*(?P<main>[^()\[\]]+?)\s*[(\[](?P<paren>[^()\[\]]*[가-힣][^()\[\]]*)[)\]]\s*$")
# "X (X)" 처럼 괄호 안이 본문과 같은 중복 표기
DUP_PAREN = re.compile(r"^\s*(?P<main>.+?)\s*[(\[](?P<paren>[^()\[\]]+)[)\]]\s*$")
# 파일 시스템에 쓸 수 없는 문자 → 비슷한 전각 문자 (yt-dlp 의 sanitize_filename 과 같은 치환)
_UNSAFE = str.maketrans({"/": "⧸", "\\": "⧹", ":": "：", "*": "＊", "?": "？", '"': "＂", "<": "＜", ">": "＞", "|": "｜", "\0": ""})


def _norm(s: str) -> str:
    return re.sub(r"[\s\W_]+", "", s or "").casefold()


def display_name(info: dict) -> str:
    """파일명에 쓸 영상명. 한글 제목이 있으면 한글을 우선한다."""
    title = (info.get("title") or "").strip()

    # 1) 제목이 "Disease (병)" 꼴 → "병"
    m = EN_WITH_KO_PAREN.match(title)
    if m:
        return m["paren"].strip()

    # 2) 제목에 한글이 이미 있으면 그대로
    if HANGUL.search(title):
        return title

    # 3) Topic 음원: 태그가 [아티스트, 아티스트(한글), 앨범, 앨범(한글), 트랙, 트랙(한글)] 순으로 붙는다
    if is_auto_generated_music(info):
        tags = [t.strip() for t in (info.get("tags") or []) if t and t.strip()]
        track = info.get("track") or title
        album = info.get("album") or ""
        for i, t in enumerate(tags[:-1]):
            if _norm(t) == _norm(track) and HANGUL.search(tags[i + 1]):
                return tags[i + 1]
        # 트랙 영문 태그가 없고 마지막 태그가 한글이면 (Agog → 아고그). 아티스트·앨범 태그는 제외
        if tags and HANGUL.search(tags[-1]) and len(tags) >= 3 and _norm(tags[-1]) not in {_norm(album), _norm(tags[0]), _norm(tags[1])}:
            return tags[-1]

    # 4) "Loosing Control (Loosing Control)" 같은 중복 괄호 제거
    m = DUP_PAREN.match(title)
    if m and _norm(m["main"]) == _norm(m["paren"]):
        return m["main"].strip()

    return title or info.get("id", "untitled")


def outtmpl_for(out_dir: Path, index: int, name: str) -> str:
    """{nn}.{영상명}.{확장자} — 파일 시스템에 안전하게, '%' 는 yt-dlp 템플릿 이스케이프"""
    safe = name.translate(_UNSAFE).strip().rstrip(".").replace("%", "%%") or "untitled"
    return str(out_dir / f"{index:02d}.{safe}.%(ext)s")


