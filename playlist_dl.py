    if args.only:
        entries = [e for e in entries if e["id"] in set(args.only)]

    decisions: list[Decision] = []
    failed: list[str] = []

    for idx, entry in enumerate(entries, start=1):
        vid = entry["id"]
        url = f"https://www.youtube.com/watch?v={vid}"
        try:
            info = fetch_info(ytdlp, url, args)
        except YtDlpError as e:
            print(f"[{idx:02d}] {vid}  ✗ 메타데이터 조회 실패: {e}")
            failed.append(vid)
            continue

        if args.force:
            mode, reason = args.force, "--force"
        else:
            mode, reason = classify(info, motion_check=not args.no_motion_check)

        name = display_name(info)
        d = Decision(
            index=idx, id=vid, title=info.get("title") or entry.get("title") or vid, name=name,
            channel=info.get("uploader") or info.get("channel") or "", duration=info.get("duration"),
            mode=mode, reason=reason, url=url,
        )
        decisions.append(d)
        tag = "♪ AUDIO" if mode == "audio" else "▶ VIDEO"
        shown = d.title if name == d.title else f"{d.title}  → {name}"
        print(f"[{idx:02d}] {tag}  {shown}  ({d.channel})  — {reason}")

        try:
            if args.dry_run:
                print(f"       → {dry_run(ytdlp, url, args, mode, base_dir, idx, name)}")
            else:
                download(ytdlp, url, args, mode, base_dir, idx, name)
        except YtDlpError as e:
            print(f"       ✗ 다운로드 실패: {e}")
            failed.append(vid)

    # 분류 결과 저장 — 다음 실행 때 MANUAL_OVERRIDES 참고용이자, 다른 머신에서 --restore 할 때의 매니페스트
    report = write_manifest(base_dir, args.url, pl_title, decisions)

    n_a = sum(d.mode == "audio" for d in decisions)
    n_v = sum(d.mode == "video" for d in decisions)
    print(f"\n완료: 음원 {n_a}개, 영상 {n_v}개, 실패 {len(failed)}개  → 분류표 {report}")
    if failed:
        print("실패한 ID:", ", ".join(failed))
    return 1 if failed else 0


